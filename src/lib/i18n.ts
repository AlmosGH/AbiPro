export type Locale = 'de' | 'hu';
export const LANGUAGE_CONTEXT = 'abipro-language';

export function resolveLocale(savedLocale: string | undefined, acceptLanguage: string | null): Locale {
	if (savedLocale === 'de' || savedLocale === 'hu') return savedLocale;

	const preferred = (acceptLanguage ?? '')
		.split(',')
		.map((entry, index) => {
			const [tag, ...parameters] = entry.trim().split(';');
			const qualityParameter = parameters.find((parameter) => parameter.trim().startsWith('q='));
			const quality = qualityParameter ? Number.parseFloat(qualityParameter.trim().slice(2)) : 1;
			const baseTag = tag?.trim().toLowerCase().split('-')[0];
			return { baseTag, quality, index };
		})
		.filter((entry) => entry.quality > 0 && (entry.baseTag === 'hu' || entry.baseTag === 'de'))
		.sort((a, b) => b.quality - a.quality || a.index - b.index)[0];

	return preferred?.baseTag === 'hu' ? 'hu' : 'de';
}

export interface LanguageContext {
	readonly locale: Locale;
	t(key: string, values?: Record<string, string | number>): string;
	setLocale(locale: Locale): void;
}

